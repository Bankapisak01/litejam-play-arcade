const fs=require('node:fs'),vm=require('node:vm'),assert=require('node:assert/strict');
const env={window:{},Image:class{},Math};
vm.runInNewContext(fs.readFileSync('dist/boss.js','utf8'),env);
const B=env.window.PunkmanBoss;
function run(b,seconds,p={x:2735,y:208,w:14,h:30}){const events=[];for(let i=0;i<Math.round(seconds*120);i++)events.push(...B.tick(b,1/120,p));return events;}
const b=B.create();assert.equal(b.hp,30);run(b,3);assert.equal(b.active,false);assert.equal(b.state,'idle','Inactive boss cannot attack');
b.active=true;let events=[];for(let i=0;i<600&&b.state!=='charge';i++)events.push(...B.tick(b,1/120,{x:2735,y:208,w:14,h:30}));
assert.equal(b.state,'charge');assert.equal(events.length,0,'Boss telegraphs before attacking');
assert.equal(b.attack,'breath');run(b,.5);assert.equal(b.state,'charge');
events=run(b,1.1);assert.equal(events.filter(e=>e.kind==='breath').length,2,'One breath attack emits exactly two volleys');
assert(events.every(e=>e.face===-1));assert.equal(b.state,'recover');
const close=B.create();close.active=true;let clawEvents=[];
for(let i=0;i<400;i++)clawEvents.push(...B.tick(close,1/120,{x:close.x-36,y:208,w:14,h:30}));
assert.equal(clawEvents.filter(e=>e.kind==='claw').length,1,'One claw strike emits one damage event');
assert(clawEvents.find(e=>e.kind==='claw').zone.w>40);
const right=B.create();right.active=true;for(let i=0;i<500&&right.state!=='charge';i++)B.tick(right,1/120,{x:3070,y:208,w:14,h:30});
assert.equal(right.face,1,'Boss can aim at a player on its right');
const stateBefore=b.state;B.hit(b);assert.equal(b.state,stateBefore,'Hit animation does not erase attack timing');assert.equal(B.pose(b).state,'hurt');run(b,.2);assert.notEqual(B.pose(b).state,'hurt');
B.defeat(b);const deathEvents=run(b,2);assert.equal(b.dead,true);assert.equal(B.pose(b).state,'death');assert.equal(B.pose(b).frame,7);
assert(!deathEvents.some(e=>e.kind==='breath'||e.kind==='claw'),'Defeated boss cannot attack');
assert.equal(deathEvents.filter(e=>e.kind==='deathBurst').length,3,'Death effects fire once each');
assert.equal(B.create().state,'idle');console.log('PASS: boss telegraphs, breath volleys, single-hit claw, facing, hurt overlay and death.');

const phase=B.create();phase.active=true;phase.hp=16;B.hit(phase);assert.equal(phase.phase,1,'Overdrive must not begin above half HP');
phase.state='breath';phase.clock=.3;phase.hp=15;
assert.equal(B.hit(phase),true,'An exact half-health hit starts the transition');
assert.equal(phase.phase,2);assert.equal(phase.state,'transform');assert.equal(phase.hp,15,'Changing phase does not heal');
assert.equal(B.pose(phase).state,'charge','Transformation overrides hurt animation');
const phaseEvents=run(phase,1.5);assert.equal(phase.state,'transform');assert(!phaseEvents.some(e=>['breath','claw','quake'].includes(e.kind)));
B.hit(phase);assert.equal(phase.phaseTransitions,1,'Further hits cannot restart the transition');
run(phase,.21);assert.equal(phase.state,'idle');
run(phase,.72);assert.equal(phase.state,'walk','Phase 2 idle is 40 percent faster');
while(phase.state!=='charge')run(phase,1/120);
assert.equal(phase.attack,'stomp','First Overdrive attack introduces Sonic Quake');
run(phase,.8);assert.equal(phase.state,'charge','New attack retains a readable wind-up');
const quakes=run(phase,1).filter(e=>e.kind==='quake');assert.equal(quakes.length,3,'Stomp emits exactly three wave pairs');
assert.equal(phase.phaseTransitions,1);
const instant=B.create();instant.active=true;instant.hp=0;assert.notEqual(B.hit(instant),true);B.defeat(instant);run(instant,2);assert.equal(instant.state,'death','Lethal hits never resurrect the boss for phase 2');
const fresh=B.create();assert.equal(fresh.phase,1);assert.equal(fresh.phaseTransitions,0);
console.log('PASS: half-health threshold, one protected transition, faster phase 2, telegraphed Sonic Quake, lethal hit and reset.');
