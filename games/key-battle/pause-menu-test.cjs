const assert = require('node:assert/strict');
const { boot, settle, noop } = require('./tests/browser-harness.cjs');

(async () => {
  const game = boot({ reducedMotion: false, viewport: { height: 768, offsetTop: 0 } });
  game.load(); await settle(); game.tick();
  const menu = game.el('#session-menu'), input = game.el('#typing-input');
  game.el('#pause').click();
  assert.equal(menu.open, true, 'The header menu must expose session setup before playing');
  assert.equal(game.snapshot().status, 'ready', 'Opening setup must not start a session');
  game.emitDocument('keydown', { key: 'Enter', target: game.document.body, preventDefault: noop });
  assert.equal(game.snapshot().status, 'ready', 'Only the explicit Start action begins a session');
  game.el('#start').click();
  assert.equal(menu.open, false, 'Starting must dismiss the setup dialog');
  assert.equal(game.snapshot().status, 'playing');
  assert.equal(game.document.activeElement, input, 'Starting must focus the typing input');
  input.handlers.keydown({ key: game.snapshot().target[0], preventDefault: noop });
  game.tick(); game.tick();
  const before = JSON.stringify(game.snapshot());
  game.el('#pause').click();
  const paused = game.snapshot();
  assert.equal(menu.open, true);
  assert.equal(paused.status, 'paused');
  assert.equal(game.el('#lesson').disabled, true, 'An active run must lock session selection');
  assert.equal(game.el('#settings-note').hidden, false, 'The menu explains how to change the session');
  assert.equal(game.document.activeElement, game.el('#resume'));
  for (let i = 0; i < 25; i++) game.tick();
  const frozen = game.snapshot();
  for (const field of ['buffer', 'target', 'elapsed', 'wordLeft', 'beatLeft', 'hp', 'bossHp', 'round']) {
    assert.equal(frozen[field], paused[field], `${field} must stay unchanged while the menu is open`);
  }
  assert.deepEqual(frozen.actors, paused.actors, 'Actor state must freeze with the menu');
  game.el('#start').click();
  assert.equal(game.snapshot().status, 'paused', 'A hidden Start action must not replace the current run');
  game.el('#lesson').value = 'sentences'; game.el('#lesson').handlers.change();
  assert.equal(game.snapshot().lesson, paused.lesson, 'Session changes must not silently reset a run');
  let prevented = false;
  game.emitDocument('keydown', { key: 'Enter', target: game.el('#sound'), preventDefault() { prevented = true; } });
  assert.equal(prevented, false, 'Menu controls retain native keyboard behavior');
  assert.equal(game.snapshot().status, 'paused');
  game.el('#sound').click();
  assert.equal(game.document.activeElement, game.el('#resume'), 'A menu setting must not send focus behind the dialog');
  let repeatedEscapePrevented = false;
  game.emitDocument('keydown', { key: 'Escape', repeat: true, target: game.el('#resume'), preventDefault() { repeatedEscapePrevented = true; } });
  if (!repeatedEscapePrevented) menu.handlers.cancel({ preventDefault: noop });
  assert.equal(game.snapshot().status, 'paused', 'Holding Escape must not trigger native cancel and immediately resume');
  assert.equal(menu.open, true);
  menu.handlers.cancel({ preventDefault: noop });
  assert.equal(menu.open, false, 'Escape closes the dialog');
  assert.equal(game.snapshot().status, 'playing', 'Escape resumes the paused run');
  assert.equal(game.document.activeElement, input, 'Resume restores typing focus');
  menu.handlers.close();
  assert.equal(game.snapshot().status, 'playing', 'The subsequent native close event must not pause again');
  const resumed = game.snapshot();
  for (const field of ['buffer', 'target', 'elapsed', 'wordLeft', 'beatLeft']) assert.equal(resumed[field], paused[field]);
  game.tick();
  assert(game.snapshot().elapsed > resumed.elapsed, 'The resumed clock must advance again');
  assert.notEqual(JSON.stringify(game.snapshot()), before);
  game.emit('blur');
  assert.equal(game.snapshot().status, 'paused', 'Unexpected blur pauses the run');
  game.emit('focus');
  assert.equal(game.snapshot().status, 'paused', 'Window focus must never resume unexpectedly');
  game.el('#resume').click();
  game.el('#pause').click(); game.el('#finish').click();
  assert.equal(game.snapshot().status, 'finished', 'End session must finish without resuming');
  assert.equal(menu.open, false);
  game.tick(); game.tick();
  assert.equal(game.el('#results').open, true, 'Ending a paused session presents its results');
  game.el('#change-session').click();
  assert.equal(game.snapshot().status, 'ready');
  assert.equal(menu.open, true, 'Change session returns to setup');
  assert.equal(game.el('#lesson').disabled, false);
  game.el('#lesson').value = 'everyday'; game.el('#lesson').handlers.change();
  assert.equal(game.snapshot().lesson, 'everyday');
  assert.equal(menu.open, true, 'Choosing a lesson keeps setup open');
  game.viewport.height = 420; game.viewport.offsetTop = 18; game.emitViewport('resize');
  assert.equal(game.document.documentElement.style['--play-viewport-height'], '420px', 'The layout tracks space above the mobile keyboard');
  console.log('PASS: setup requires explicit Start; modal pause preserves clocks, word and actors; cancel resumes once; settings stay isolated; end/change flow and keyboard viewport work.');
})().catch(error => { console.error(error); process.exitCode = 1; });
